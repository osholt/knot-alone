String _type1({
  required int mmsi,
  required double latitude,
  required double longitude,
  required double speedKnots,
  required double courseDegrees,
  required int headingDegrees,
  required int second,
  required int navigationStatus,
}) {
  final bits = _Bits(168)
    ..unsigned(0, 6, 1)
    ..unsigned(8, 30, mmsi)
    ..unsigned(38, 4, navigationStatus)
    ..signed(42, 8, -128)
    ..unsigned(50, 10, (speedKnots * 10).round())
    ..unsigned(60, 1, 1)
    ..signed(61, 28, (longitude * 600000).round())
    ..signed(89, 27, (latitude * 600000).round())
    ..unsigned(116, 12, (courseDegrees * 10).round())
    ..unsigned(128, 9, headingDegrees)
    ..unsigned(137, 6, second);
  return _single(bits.payload());
}

