String _single(({String payload, int fillBits}) encoded) =>
    _sentence('AIVDM,1,1,,A,${encoded.payload},${encoded.fillBits}');

String _sentence(String body) {
  var checksum = 0;
  for (final code in body.codeUnits) {
    checksum ^= code;
  }
  return '!$body*${checksum.toRadixString(16).padLeft(2, '0').toUpperCase()}';
}

class _Bits {
  _Bits(int length) : _values = List.filled(length, 0);

  final List<int> _values;

  void unsigned(int start, int length, int value) {
    for (var offset = 0; offset < length; offset += 1) {
      final shift = length - offset - 1;
      _values[start + offset] = (value >> shift) & 1;
    }
  }

  void signed(int start, int length, int value) {
    unsigned(start, length, value < 0 ? (1 << length) + value : value);
  }

  void text(int start, int length, String value) {
    final padded = value.toUpperCase().padRight(length ~/ 6, '@');
    for (var index = 0; index < length ~/ 6; index += 1) {
      final encoded = _alphabet.indexOf(padded[index]);
      unsigned(start + index * 6, 6, encoded < 0 ? 32 : encoded);
    }
  }

  ({String payload, int fillBits}) payload() {
    final fillBits = (6 - _values.length % 6) % 6;
    final padded = [..._values, ...List.filled(fillBits, 0)];
    final output = StringBuffer();
    for (var index = 0; index < padded.length; index += 6) {
      var value = 0;
      for (var bit = 0; bit < 6; bit += 1) {
        value = (value << 1) | padded[index + bit];
      }
      output.writeCharCode(value < 40 ? value + 48 : value + 56);
    }
    return (payload: output.toString(), fillBits: fillBits);
  }
}
