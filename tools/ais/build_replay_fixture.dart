List<String> _type5({
  required int mmsi,
  required String name,
  required String callSign,
  required int shipType,
  required String sequence,
}) {
  final bits = _Bits(424)
    ..unsigned(0, 6, 5)
    ..unsigned(8, 30, mmsi)
    ..text(70, 42, callSign)
    ..text(112, 120, name)
    ..unsigned(232, 8, shipType);
  final encoded = bits.payload();
  final split = encoded.payload.length ~/ 2;
  return [
    _sentence('AIVDM,2,1,$sequence,A,${encoded.payload.substring(0, split)},0'),
    _sentence(
      'AIVDM,2,2,$sequence,A,${encoded.payload.substring(split)},${encoded.fillBits}',
    ),
  ];
}

